/**
 * Returns all 36 Indian states and union territories in alphabetical order.
 */
export function getAllIndianStates(): string[] {
  return [...INDIAN_STATES_AND_UTS];
}

/**
 * Returns cities for a given Indian state.
 * Returns empty array if state is invalid or unselected.
 */
export function getCitiesForIndianState(state: string): string[] {
  if (!state) return [];
  const found = Object.keys(INDIAN_STATE_CITIES_MAP).find(
    (s) => s.toLowerCase() === state.trim().toLowerCase()
  );
  return found ? INDIAN_STATE_CITIES_MAP[found] : [];
}

/**
 * Checks if a state name is a valid Indian state or union territory.
 */
export function isValidIndianState(state: string): boolean {
  if (!state) return false;
  return INDIAN_STATES_AND_UTS.some((s) => s.toLowerCase() === state.trim().toLowerCase());
}

/**
 * Checks if a city is valid for the given state.
 */
export function isValidCityForState(state: string, city: string): boolean {
  if (!state || !city) return false;
  const cities = getCitiesForIndianState(state);
  return cities.some((c) => c.toLowerCase() === city.trim().toLowerCase());
}
