export const OTHER_CITY_OPTION = 'Other city';

/**
 * Return all state names sorted alphabetically
 */
export function getIndianStateNames(): string[] {
  return INDIAN_STATES_AND_UT.map((s) => s.name).sort();
}

/**
 * Return cities for a given state name including the 'Other city' choice
 */
export function getCitiesForState(stateName: string): string[] {
  const match = INDIAN_STATES_AND_UT.find(
    (s) => s.name.toLowerCase() === stateName.trim().toLowerCase()
  );
  if (!match) return [OTHER_CITY_OPTION];
  return [...match.cities.sort(), OTHER_CITY_OPTION];
}
