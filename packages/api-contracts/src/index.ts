export interface ApiResponse<T = any> {
  success: true;
  data: T;
  meta?: Record<string, any>;
  timestamp: string;
}

export interface ApiErrorBody {
  code: string;
  message: string;
  requestId?: string;
  details?: any;
}

export interface ApiErrorResponse {
  success: false;
  error: ApiErrorBody;
  timestamp: string;
}

export type StandardResponse<T> = ApiResponse<T> | ApiErrorResponse;

